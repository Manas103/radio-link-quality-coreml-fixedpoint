"""Quantize the trained CNN to INT8 weights with an integer-only requantization
path (TFLite-style fixed-point multiplier + right-shift, all integer ops),
and export it as a C header plus a float reference dump for the C program's
own harness to diff against.

Per-channel symmetric weight quantization (one scale per output channel,
scale = max_abs_weight_for_that_channel / 127), which is what real int8
inference stacks use because a single per-tensor scale is dominated by
whichever channel happens to have the largest weight. Per-layer activation
scales are calibrated from the max absolute activation observed over a
1000-window calibration slice of the training split (never the held-out
test/parity set). Biases are requantized into the accumulator's pre-shift
integer domain so the whole conv/linear path is integer add and multiply;
only the very last step (dequantizing the final accumulator and applying
sigmoid) uses floating point, which is disclosed in the README.
"""
import json
import sys

import numpy as np
import torch

sys.path.insert(0, "src")
from datagen import build_dataset, normalize, split  # noqa: E402
from model import LinkDegradationCNN  # noqa: E402

WINDOW_LEN = 64


def quantize_per_out_channel(w, bits=8):
    """w: [Cout, Cin, K] (or [Cout, Cin] for the fc layer). Returns (q_int8, scales[Cout])."""
    qmax = 2 ** (bits - 1) - 1
    cout = w.shape[0]
    flat = w.reshape(cout, -1)
    scales = np.max(np.abs(flat), axis=1) / qmax
    scales = np.where(scales == 0, 1.0, scales)
    q = np.round(flat / scales[:, None]).clip(-qmax - 1, qmax).astype(np.int32)
    return q.reshape(w.shape), scales


def decompose_multiplier(real_multiplier):
    """real_multiplier -> (M int32, shift) such that acc*real_multiplier ~= (acc*M) >> shift."""
    if real_multiplier <= 0:
        return 0, 0
    shift = 31
    m = real_multiplier * (2 ** 31)
    while m >= 2 ** 31 and shift > 0:
        m /= 2.0
        shift -= 1
    return int(round(m)), shift


def decompose_multipliers_per_channel(real_multipliers):
    ms, shs = [], []
    for rm in real_multipliers:
        m, sh = decompose_multiplier(float(rm))
        ms.append(m)
        shs.append(sh)
    return np.array(ms, dtype=np.int64), np.array(shs, dtype=np.int64)


def calibrate_activation_scales(model, Xcal):
    """Scale from the calibration-set max |activation| per layer. A 99.9th
    percentile calibration was also tried (attempt 3, see README Findings):
    it lowered the mean parity error slightly but raised the max parity
    error, because the claim is a max-abs-diff claim, max-based calibration
    (this one) is the version kept."""
    with torch.no_grad():
        x = torch.from_numpy(Xcal)
        a0 = x
        a1 = torch.relu(model.conv1(a0))
        a2 = torch.relu(model.conv2(a1))
        a3 = torch.relu(model.conv3(a2))

    def mx(t):
        return float(t.abs().max().item())

    acts = {"input": mx(a0), "relu1": mx(a1), "relu2": mx(a2), "relu3": mx(a3)}
    return acts


def q_bias_per_channel(bias, scale_in, scales_w):
    return np.round(bias / (scale_in * scales_w)).astype(np.int64).clip(-2 ** 31, 2 ** 31 - 1).astype(np.int32)


def export_c_header(path, params):
    lines = ["// Auto-generated by src/quantize.py. Do not hand-edit.",
             "#ifndef RADIO_WEIGHTS_H", "#define RADIO_WEIGHTS_H", ""]

    def arr(name, data, ctype):
        flat = np.asarray(data).reshape(-1)
        body = ", ".join(str(int(v)) for v in flat)
        lines.append(f"static const {ctype} {name}[{flat.size}] = {{{body}}};")

    dims = params["dims"]
    for k, v in dims.items():
        lines.append(f"#define {k} {v}")
    lines.append("")

    arr("CONV1_W", params["conv1_w"], "int8_t")
    arr("CONV1_B", params["conv1_b"], "int32_t")
    arr("CONV2_W", params["conv2_w"], "int8_t")
    arr("CONV2_B", params["conv2_b"], "int32_t")
    arr("CONV3_W", params["conv3_w"], "int8_t")
    arr("CONV3_B", params["conv3_b"], "int32_t")
    arr("FC_W", params["fc_w"], "int8_t")
    arr("FC_B", params["fc_b"], "int32_t")

    for layer in ("conv1", "conv2", "conv3"):
        arr(f"{layer.upper()}_MULT", params[layer + "_mult"], "int32_t")
        arr(f"{layer.upper()}_SHIFT", params[layer + "_shift"], "int32_t")

    lines.append(f"static const float INPUT_SCALE = {float(params['input_scale'])!r}f;")
    lines.append(f"static const float OUTPUT_SCALE = {float(params['output_scale'])!r}f;")
    lines.append("")
    lines.append("#endif")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    model = LinkDegradationCNN()
    model.load_state_dict(torch.load("data/model.pt"))
    model.eval()

    X, y = build_dataset()
    (Xtr, ytr), (Xva, yva), (Xte, yte) = split(X, y)
    stats_npz = np.load("data/norm_stats.npz")
    stats = (stats_npz["mean"], stats_npz["std"])
    Xtr_n, _ = normalize(Xtr, stats)
    Xte_n, _ = normalize(Xte, stats)

    rng = np.random.default_rng(0)
    cal_idx = rng.choice(len(Xtr_n), size=min(1000, len(Xtr_n)), replace=False)
    Xcal = Xtr_n[cal_idx]
    acts = calibrate_activation_scales(model, Xcal)
    print("calibrated activation max-abs:", acts)

    qmax = 127
    s_in = acts["input"] / qmax
    s_r1 = acts["relu1"] / qmax
    s_r2 = acts["relu2"] / qmax
    s_r3 = acts["relu3"] / qmax
    # The global-average-pool layer sums and divides int8 values that are
    # already in relu3's scale without ever requantizing, so the pooled
    # vector's true scale is s_r3, not a separately calibrated "pooled" scale.

    w1 = model.conv1.weight.detach().numpy()
    b1 = model.conv1.bias.detach().numpy()
    w2 = model.conv2.weight.detach().numpy()
    b2 = model.conv2.bias.detach().numpy()
    w3 = model.conv3.weight.detach().numpy()
    b3 = model.conv3.bias.detach().numpy()
    wf = model.fc.weight.detach().numpy()
    bf = model.fc.bias.detach().numpy()

    q1, sw1 = quantize_per_out_channel(w1)
    q2, sw2 = quantize_per_out_channel(w2)
    q3, sw3 = quantize_per_out_channel(w3)
    qf, swf = quantize_per_out_channel(wf)

    b1q = q_bias_per_channel(b1, s_in, sw1)
    b2q = q_bias_per_channel(b2, s_r1, sw2)
    b3q = q_bias_per_channel(b3, s_r2, sw3)
    bfq = q_bias_per_channel(bf, s_r3, swf)

    m1, sh1 = decompose_multipliers_per_channel((s_in * sw1) / s_r1)
    m2, sh2 = decompose_multipliers_per_channel((s_r1 * sw2) / s_r2)
    m3, sh3 = decompose_multipliers_per_channel((s_r2 * sw3) / s_r3)

    output_scale = s_r3 * swf[0]

    dims = dict(IN_CH=3, C1=w1.shape[0], C2=w2.shape[0], C3=w3.shape[0],
                K1=w1.shape[2], K2=w2.shape[2], K3=w3.shape[2], WINDOW=WINDOW_LEN)

    params = dict(
        dims=dims,
        conv1_w=q1.astype(np.int8), conv1_b=b1q,
        conv2_w=q2.astype(np.int8), conv2_b=b2q,
        conv3_w=q3.astype(np.int8), conv3_b=b3q,
        fc_w=qf.astype(np.int8), fc_b=bfq,
        conv1_mult=m1, conv1_shift=sh1,
        conv2_mult=m2, conv2_shift=sh2,
        conv3_mult=m3, conv3_shift=sh3,
        input_scale=s_in, output_scale=output_scale,
    )
    export_c_header("c/weights.h", params)

    weight_bytes = q1.size + q2.size + q3.size + qf.size
    print("INT8 weight bytes:", weight_bytes, "=", round(weight_bytes / 1024.0, 3), "KB")

    # Export the 2,000-window held-out parity/timing set as raw float32 for the
    # C harness, plus the PyTorch float reference probabilities to diff against.
    n_parity = 2000
    Xp = Xte_n[:n_parity]
    with torch.no_grad():
        logits = model(torch.from_numpy(Xp))
        probs = torch.sigmoid(logits).numpy()
    Xp.astype(np.float32).tofile("data/parity_windows.f32")
    probs.astype(np.float32).tofile("data/parity_reference_probs.f32")

    with open("docs/quantize_report.json", "w") as f:
        json.dump(dict(
            activation_scales=acts,
            weight_bytes=weight_bytes,
            weight_kb=round(weight_bytes / 1024.0, 3),
            n_parity_windows=n_parity,
            quantization="per-output-channel symmetric int8, TFLite-style int32 multiplier + shift requantization",
        ), f, indent=2)
    print("wrote c/weights.h, data/parity_windows.f32, data/parity_reference_probs.f32")


if __name__ == "__main__":
    main()
